export const documentMessages = { en, ru, uz };
const titleKeys = {
  quotation: "quotation", "sales-order": "salesOrder", invoice: "invoice",
  "packing-list": "packingList", "delivery-note": "deliveryNote",
  "purchase-order": "purchaseOrder", "material-receipt": "materialReceipt",
  "manufacturing-order": "manufacturingOrder",
  "technical-specification": "technicalSpecification",
  "material-requirements": "materialRequirements",
} as const;
const labelKeys = Object.fromEntries(
  Object.entries(en).map(([key, value]) => [value, key]),
) as Record<string, keyof typeof en>;
export function documentTitle(kind: keyof typeof titleKeys, locale: Locale) {
  return documentMessages[locale][titleKeys[kind]];
}
export function documentLabel(value: string, locale: Locale) {
  const key = labelKeys[value];
  return key ? documentMessages[locale][key] : value;
}
